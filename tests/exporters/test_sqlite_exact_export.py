@pytest.mark.parametrize("declaration", DECLARATIONS)
@pytest.mark.parametrize("value", VALUES, ids=str)
def test_stored_values_match_previous_export_or_explicitly_reject(tmp_path, monkeypatch, declaration, value):
    create = f"CREATE TABLE t(v {declaration})"
    monkeypatch.setattr(DataTable, "__init__", lambda *args, **kwargs: None)
    monkeypatch.setattr(DataTable, "create_table", lambda *args, **kwargs: create)
    old_value = value if value is None or isinstance(value, (int, float, str, bytes)) else str(value)
    with closing(sqlite3.connect(":memory:")) as old, old:
        old.execute(create)
        try:
            old.execute("INSERT INTO t VALUES (?)", (old_value,))
        except (OverflowError, sqlite3.Error) as exc:
            with pytest.raises(type(exc)):
                export_sqlite(str(tmp_path / "new.db"), ["v"], [(value,)], False, "t")
            return
        previous = old.execute("SELECT quote(v), typeof(v), v FROM t").fetchone()
    try:
        export_sqlite(str(tmp_path / "new.db"), ["v"], [(value,)], False, "t")
    except ErrInfo:
        assert isinstance(value, Decimal)
        assert previous[1] in ("integer", "real") or value.is_nan()
        if not value.is_nan():
            assert Decimal(repr(previous[2])) != value
    else:
        if isinstance(value, Decimal) and value.is_infinite() and declaration not in ("", "blob", "varchar"):
            assert snapshot(tmp_path / "new.db") == [(previous_inf_quote(value), "real")]
        else:
            assert snapshot(tmp_path / "new.db") == [previous[:2]]


@pytest.mark.parametrize("failure", [RuntimeError, KeyboardInterrupt, SystemExit, "commit"])
def test_failure_after_destination_write_rolls_back(tmp_path, monkeypatch, failure):
    path = tmp_path / "out.db"
    seed(path)
    connect = sqlite3.connect

    class FailingConnection(sqlite3.Connection):
        def executemany(self, sql, rows):
            result = super().executemany(sql, rows)
            if failure != "commit":
                raise failure("injected after INSERT")
            return result

        def commit(self):
            if failure == "commit":
                raise RuntimeError("injected before COMMIT")
            return super().commit()

    def intercepted_connect(database, *args, **kwargs):
        if str(database) == str(path):
            kwargs["factory"] = FailingConnection
        return connect(database, *args, **kwargs)

    monkeypatch.setattr(sqlite3, "connect", intercepted_connect)
    error = RuntimeError if failure == "commit" else failure
    with pytest.raises(error):
        export_sqlite(str(path), ["v"], [(1,), (2,)], False, "t")
    assert snapshot(path) == [("'keep me'", "text")]
    with closing(connect(path)) as db, db:
        assert db.execute("SELECT name FROM sqlite_master WHERE type='index'").fetchall() == [("original_index",)]
        db.execute("INSERT INTO t VALUES ('unlocked')")


@pytest.mark.parametrize(
    "value",
    ["0.1", "1.10", "1234567890.1234567891", "12345678901234567890", "9223372036854775807"],
)
def test_duckdb_decimal_query_to_sqlite(tmp_path, value):
    pytest.importorskip("duckdb")
    from execsql.db.duckdb import DuckDBDatabase
    from execsql.exporters.sqlite import write_query_to_sqlite

    source = DuckDBDatabase(":memory:")
    path = tmp_path / "out.db"
    seed(path)
    try:
        scale = 0 if value == "9223372036854775807" else 10
        query = f"SELECT CAST('{value}' AS DECIMAL(38,{scale})) AS v"
        if value in ("1234567890.1234567891", "12345678901234567890"):
            with pytest.raises(ErrInfo, match="SQLite"):
                write_query_to_sqlite(query, source, str(path), False, "t")
            assert snapshot(path) == [("'keep me'", "text")]
        else:
            write_query_to_sqlite(query, source, str(path), False, "t")
            with closing(sqlite3.connect(path)) as db, db:
                actual = db.execute("SELECT v FROM t").fetchone()[0]
            assert Decimal(repr(actual)) == Decimal(value)
    finally:
        source.close()


@pytest.mark.parametrize("value", ["0.1", "1234567890.1234567891"])
def test_export_metacommand_decimal_contract(tmp_path, value):
    pytest.importorskip("duckdb")
    import execsql

    path = tmp_path / "out.db"
    seed(path)
    script = tmp_path / "export.sql"
    script.write_text(
        "CREATE TABLE amounts(v DECIMAL(20,10));\n"
        f"INSERT INTO amounts VALUES ('{value}');\n"
        f'-- !x! EXPORT amounts TO "{path}" AS SQLITE\n',
    )
    result = execsql.run(script, dsn="duckdb:///:memory:")
    assert result.success == (value == "0.1")
    if result.success:
        with closing(sqlite3.connect(path)) as db, db:
            actual = db.execute("SELECT v FROM amounts").fetchone()[0]
        assert Decimal(repr(actual)) == Decimal(value)
    else:
        assert "SQLite" in result.errors[0].message
        assert snapshot(path) == [("'keep me'", "text")]
        with closing(sqlite3.connect(path)) as db, db:
            assert not db.execute("SELECT name FROM sqlite_master WHERE name='amounts'").fetchall()
