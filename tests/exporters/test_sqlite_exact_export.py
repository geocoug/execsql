def previous_inf_quote(value):
    with closing(sqlite3.connect(":memory:")) as db, db:
        return db.execute("SELECT quote(?)", (float(value),)).fetchone()[0]


def snapshot(path):
    with closing(sqlite3.connect(path)) as db, db:
        return db.execute('SELECT quote(v), typeof(v) FROM "t"').fetchall()


def seed(path):
    with closing(sqlite3.connect(path)) as db, db:
        db.execute("CREATE TABLE t(v TEXT)")
        db.execute("INSERT INTO t VALUES ('keep me')")
        db.execute("CREATE INDEX original_index ON t(v)")


@pytest.mark.parametrize("value", ["1234567890.1234567891", "12345678901234567890", "NaN", "sNaN", "1e9999", "1e-9999"])
@pytest.mark.parametrize("existing", [False, True])
def test_lossy_decimal_rejected_before_destination_change(tmp_path, value, existing):
    path = tmp_path / "out.db"
    if existing:
        seed(path)
    before = path.read_bytes() if existing else None
    with pytest.raises(ErrInfo, match="SQLite"):
        export_sqlite(str(path), ["v"], [(Decimal(value),)], False, "t")
    if existing:
        assert path.read_bytes() == before
        assert snapshot(path) == [("'keep me'", "text")]
    else:
        assert not path.exists()


@pytest.mark.parametrize("failure", ["read", "bind", "interrupt", "ddl"])
def test_failed_replacement_restores_table_and_index(tmp_path, failure):
    path = tmp_path / "out.db"
    seed(path)

    def rows():
        yield (1,)
        if failure == "read":
            raise RuntimeError("source failed")
        if failure == "interrupt":
            raise KeyboardInterrupt
        # Oversized native integers fail during binding, after replacement DDL.
        yield (2**100,) if failure == "bind" else (2,)

    headers = ["v", "v"] if failure == "ddl" else ["v"]
    with pytest.raises((RuntimeError, OverflowError, KeyboardInterrupt, sqlite3.OperationalError)):
        export_sqlite(str(path), headers, rows(), False, "t")
    assert snapshot(path) == [("'keep me'", "text")]
    with closing(sqlite3.connect(path)) as db, db:
        assert db.execute("SELECT name FROM sqlite_master WHERE type='index'").fetchall() == [("original_index",)]
        db.execute("INSERT INTO t VALUES ('unlocked')")


@pytest.mark.parametrize(
    "value",
    [
        "0.1",
        "1.10",
        "2.00",
        "-0.00",
        "9223372036854775807",
        "9007199254740993",
        "0.0000001000",
        "123456789012345.6",
        "Infinity",
        "-Infinity",
    ],
)
def test_accepted_decimal_reads_back_equal(tmp_path, value):
    path = tmp_path / "out.db"
    source = Decimal(value)
    export_sqlite(str(path), ["v"], [(source,)], False, "t")
    with closing(sqlite3.connect(path)) as db, db:
        actual, kind = db.execute("SELECT v, typeof(v) FROM t").fetchone()
    assert kind in ("integer", "real")
    assert Decimal(repr(actual)) == source


def test_decimal_in_text_column_keeps_spelling(tmp_path):
    path = tmp_path / "out.db"
    export_sqlite(str(path), ["v"], [("text",), (Decimal("1.1000000000000000001"),)], False, "t")
    assert snapshot(path) == [("'text'", "text"), ("'1.1000000000000000001'", "text")]


